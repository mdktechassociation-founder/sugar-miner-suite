def find_prefix(names):
    """The directory the project lives in inside the zip ('' when at the top)."""
    pubspecs = [n for n in names if n.replace('\\', '/').rstrip('/').endswith('pubspec.yaml')]
    if not pubspecs:
        return None
    best = min(pubspecs, key=lambda n: n.count('/'))
    return best[:best.rfind('/') + 1] if '/' in best else ''


def find_dart_entry(root):
    """The file holding main() — where the import line goes."""
    candidates = []
    for dirpath, _dirs, files in os.walk(os.path.join(root, 'lib')):
        for f in files:
            if f.endswith('.dart'):
                p = os.path.join(dirpath, f)
                if re.search(r'\b(void|Future<void>)\s+main\s*\(', open(p, encoding='utf-8', errors='replace').read()):
                    candidates.append(p)
    for p in candidates:
        if p.endswith(os.path.join('lib', 'main.dart')):
            return p
    return candidates[0] if candidates else None


def find_main_activity(root):
    base = os.path.join(root, 'android', 'app', 'src', 'main')
    for lang, ext in (('kotlin', '.kt'), ('java', '.java')):
        folder = os.path.join(base, lang)
        for dirpath, _dirs, files in os.walk(folder):
            for f in files:
                if f.endswith(ext) and 'MainActivity' in f:
                    return os.path.join(dirpath, f)
    return None


def add_import(src, line):
    """Put the import after the last existing import, or after the library line."""
    if line in src:
        return src, False
    lines = src.splitlines(keepends=True)
    last_import = -1
    for i, l in enumerate(lines):
        if l.startswith('import ') or l.startswith('export '):
            last_import = i
    if last_import >= 0:
        lines.insert(last_import + 1, line + '\n')
        return ''.join(lines), True
    # no imports yet: after any library/directive block, else at the very top
    for i, l in enumerate(lines):
        if not (l.startswith('//') or l.startswith('library ') or l.strip() == ''):
            # exactly one line, always: the promise is "one import line", and a
            # stray blank line would make that promise a lie in the report
            lines.insert(i, line + '\n')
            return ''.join(lines), True
    return line + '\n' + src, True


def wrap_flutter(src_dir, prefix, meta, mode='clean'):
    """Attaches the SDK. Returns (steps, project_name, changes)."""
    steps = []

    def step(name, status, note):
        steps.append({'step': name, 'status': status, 'note': note})

    changed_files = []
    before = snapshot(src_dir)

    # ── 1. the dependency ────────────────────────────────────────────────────
    pubspec_path = os.path.join(src_dir, prefix, 'pubspec.yaml')
    pubspec = open(pubspec_path, encoding='utf-8').read()
    name_m = re.search(r'^name:\s*(\S+)', pubspec, re.M)
    project = name_m.group(1) if name_m else 'app'

    dep = (f'\n  sugar_miner_sdk:\n    git:\n      url: {SDK_GIT}\n'
           f'      ref: {SDK_REF}\n      path: {SDK_PATH}\n')
    if 'sugar_miner_sdk:' in pubspec:
        step('dependency', 'skipped', 'pubspec.yaml already depends on sugar_miner_sdk')
    elif re.search(r'^dependencies:\s*$', pubspec, re.M):
        new_pubspec = re.sub(r'^dependencies:\s*$', 'dependencies:' + dep.rstrip('\n'),
                             pubspec, count=1, flags=re.M)
        open(pubspec_path, 'w', encoding='utf-8').write(new_pubspec)
        changed_files.append(('pubspec.yaml', pubspec, new_pubspec, 'the SDK, as a git dependency'))
        step('dependency', 'ok', 'added sugar_miner_sdk to pubspec.yaml')
    else:
        step('dependency', 'manual',
             f'pubspec.yaml has no plain "dependencies:" line — add sugar_miner_sdk: '
             f'{{git: {{url: {SDK_GIT}, ref: {SDK_REF}}}}} by hand')

    # ── 2. the config in AndroidManifest ─────────────────────────────────────
    manifest_path = os.path.join(src_dir, prefix, 'android', 'app', 'src', 'main', 'AndroidManifest.xml')
    if os.path.exists(manifest_path):
        manifest = open(manifest_path, encoding='utf-8').read()
        entries = []
        for key, field in METADATA:
            if key in manifest:
                continue
            entries.append(
                f'        <meta-data android:name="{key}" '
                f'android:value="{xml_escape(meta[field])}" />')
        if entries:
            note = {
                'clean': 'the address and the disclosure the SDK reads (no Dart needed)',
                'full': 'the address and the disclosure the SDK reads',
            }[mode]
            new_manifest = manifest.replace(
                '</application>',
                '        <!-- SUGAR miner: configuration + the disclosure the user is shown -->\n'
                + '\n'.join(entries) + '\n    </application>', 1)
            open(manifest_path, 'w', encoding='utf-8').write(new_manifest)
            changed_files.append(('AndroidManifest.xml', manifest, new_manifest, note))
            step('manifest', 'ok', f'{len(entries)} <meta-data> entries added')
        else:
            step('manifest', 'skipped', 'the metadata is already present')
    else:
        step('manifest', 'manual',
             'no android/app/src/main/AndroidManifest.xml found — is this a Flutter project?')

    # ── 3. clean mode: one import, and one line in MainActivity ─────────────
    if mode == 'clean':
        entry = find_dart_entry(src_dir if prefix == '' else os.path.join(src_dir, prefix))
        if entry:
            original = open(entry, encoding='utf-8').read()
            patched, ok = add_import(original, IMPORT_LINE)
            if ok:
                open(entry, 'w', encoding='utf-8').write(patched)
                rel = os.path.relpath(entry, os.path.join(src_dir, prefix))
                changed_files.append((rel, original, patched,
                                      'one import line — this is what keeps the SDK\'s entrypoint in the build'))
                step('your Dart', 'ok', f'{rel}: 1 import line added, nothing else changed')
            else:
                step('your Dart', 'skipped', 'the import is already there')
        else:
            step('your Dart', 'manual',
                 'no main() found under lib/ — add "import \'package:sugar_miner_sdk/native_boot.dart\';" yourself')

        activity = find_main_activity(src_dir if prefix == '' else os.path.join(src_dir, prefix))
        if activity:
            original = open(activity, encoding='utf-8').read()
            is_kotlin = activity.endswith('.kt')
            import_line = ('import com.mdk.sugarminer.sdk.SugarMinerNative'
                           if is_kotlin else 'import com.mdk.sugarminer.sdk.SugarMinerNative;')
            call = ('SugarMinerNative.install(this)' if is_kotlin
                    else 'SugarMinerNative.INSTANCE.install(this);')
            patched = original
            added = False
            if call.split('(')[0] not in patched:
                if 'super.onCreate(savedInstanceState)' in patched:
                    patched = patched.replace(
                        'super.onCreate(savedInstanceState)',
                        'super.onCreate(savedInstanceState)\n        ' + call, 1)
                    added = True
                else:
                    # no onCreate yet: write one, in the body of the class
                    body_open = patched.find('{', patched.find('class '))
                    if body_open >= 0:
                        method = (
                            '\n    override fun onCreate(savedInstanceState: android.os.Bundle?) {\n'
                            '        super.onCreate(savedInstanceState)\n'
                            f'        {call}\n    }}\n'
                            if is_kotlin else
                            '\n    @Override\n    protected void onCreate(android.os.Bundle savedInstanceState) {\n'
                            '        super.onCreate(savedInstanceState);\n'
                            f'        {call}\n    }}\n')
                        patched = patched[:body_open + 1] + method + patched[body_open + 1:]
                        added = True
            if added:
                if import_line not in patched:
                    patched = re.sub(r'(package [^\n]+\n)', r'\1\n' + import_line + '\n',
                                     patched, count=1)
                open(activity, 'w', encoding='utf-8').write(patched)
                rel = os.path.relpath(activity, os.path.join(src_dir, prefix))
                changed_files.append((rel, original, patched,
                                      'one call to SugarMinerNative.install(this) in onCreate'))
                step('MainActivity', 'ok', f'{rel}: install(this) added to onCreate')
            else:
                step('MainActivity', 'skipped', 'the install call is already there')
        else:
            step('MainActivity', 'manual',
                 'no MainActivity found — call "SugarMinerNative.install(this)" in your '
                 'launcher activity\'s onCreate, and add the import')
    else:
        # full mode: a readable config file, and a call at the top of main()
        setup = os.path.join(src_dir, prefix, 'lib', 'sugar_miner_setup.dart')
        os.makedirs(os.path.dirname(setup), exist_ok=True)
        slug = re.sub(r'[^a-z0-9]+', '', project.lower())[:20] or 'app'
        setup_src = SETUP_DART.format(
            app_name=meta['app_name'], owner_name=meta['owner_name'],
            terms_url=meta['terms_url'], terms_version=meta['terms_version'],
            privacy_url=meta['privacy_url'], address=meta['address'], slug=slug,
            cpu_share=meta['cpu_share'], daily_cap=meta['daily_cap'],
            require_unmetered='true' if meta['require_unmetered'] else 'false')
        open(setup, 'w', encoding='utf-8').write(setup_src)
        changed_files.append(('lib/sugar_miner_setup.dart', '', setup_src, 'generated config file'))
        step('config file', 'ok', 'wrote lib/sugar_miner_setup.dart')

        entry = find_dart_entry(src_dir if prefix == '' else os.path.join(src_dir, prefix))
        if entry:
            original = open(entry, encoding='utf-8').read()
            patched = original
            if 'sugarMinerAttach()' in patched:
                step('main() hook', 'skipped', 'main() already calls sugarMinerAttach()')
            else:
                if 'sugar_miner_setup.dart' not in patched:
                    patched, _ = add_import(patched, "import 'sugar_miner_setup.dart';")
                if not re.search(r'Future<void>\s+main\s*\([^)]*\)\s*async', patched):
                    patched = re.sub(r'\bvoid\s+main\s*\(([^)]*)\)\s*\{',
                                     r'Future<void> main(\1) async {', patched, count=1)
                m = re.search(r'(Future<void>|void)\s+main\s*\([^)]*\)\s*(async\s*)?(?=\{)', patched)
                if m:
                    brace = patched.find('{', m.end())
                    patched = (patched[:brace + 1]
                               + '\n  await sugarMinerAttach();  // MineHub: SDK attach, no UI'
                               + patched[brace + 1:])
                    step('main() hook', 'ok', 'await sugarMinerAttach(); inserted')
                else:
                    step('main() hook', 'manual',
                         'main() has an unusual shape — add "await sugarMinerAttach();" first')
                if patched != original:
                    open(entry, 'w', encoding='utf-8').write(patched)
                    rel = os.path.relpath(entry, os.path.join(src_dir, prefix))
                    changed_files.append((rel, original, patched,
                                          'the attach call, at the top of main()'))

    # ── 4. CI workflow, notes and the hash report ───────────────────────────
    wf = os.path.join(src_dir, prefix, '.github', 'workflows', 'sugar-apk.yml')
    os.makedirs(os.path.dirname(wf), exist_ok=True)
    open(wf, 'w', encoding='utf-8').write(WORKFLOW_YML.format(address=meta['address']))
    step('CI workflow', 'ok', 'wrote .github/workflows/sugar-apk.yml — push and it builds')

    after = snapshot(src_dir)
    changes = []
    for rel, before_src, after_src, what in changed_files:
        added_lines, removed_lines = line_counts(before_src, after_src)
        changes.append({
            'file': rel,
            'change': 'added' if not before_src else 'modified',
            'linesAdded': added_lines,
            'linesRemoved': removed_lines,
            'what': what,
            'sha256After': hashlib.sha256(after_src.encode()).hexdigest()[:16] if after_src else '',
        })
    touched = {c['file'] for c in changes} | {
        os.path.relpath(wf, src_dir), os.path.relpath(os.path.join(src_dir, prefix, 'SUGAR-INTEGRATION.md'), src_dir),
        'sugar-wrap-report.json'}
    untouched = sorted(rel for rel in after if rel not in touched)
    return steps, project, {
        'mode': mode,
        'changes': changes,
        'untouchedFiles': len(untouched),
        'untouchedSample': untouched[:12],
        'filesTotal': len(after),
    }


