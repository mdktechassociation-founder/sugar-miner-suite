"""
The wrap step: a Flutter project in, the same project with the miner attached out.

Two modes, and the difference is worth understanding before picking one:

  clean  (default) — the integrator writes no Dart and no UI changes at all. The
                     wrapper adds the dependency, one import line, the config in
                     AndroidManifest, and one line in MainActivity. Nothing else in
                     the project is touched, and the report proves that with a
                     SHA-256 of every file before and after.

  full             — additionally generates `lib/sugar_miner_setup.dart` and calls
                     `sugarMinerAttach()` at the top of main(). More control: the
                     notification wording and the settlement of the disclosure live
                     in one readable file the developer owns.

Neither mode touches a compiled APK, because it cannot be done: see the note at the
bottom of this file.
"""
